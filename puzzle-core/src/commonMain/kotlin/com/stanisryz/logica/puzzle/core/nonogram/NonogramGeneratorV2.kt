    const val SIZE = 10

    /** The picture keys, in the frozen order. */
    val KEYS: List<String> get() = PICTURES.map { it.first }

    val COUNT: Int get() = PICTURES.size

    fun pictureFor(seed: PuzzleSeed): List<Boolean> = picture(indexFor(seed))

    fun picture(index: Int): List<Boolean> = PICTURES[index].second.filter { it != '/' }.map { it == '#' }

    /** The picture index of [seed]: position `seed mod COUNT` in cycle `seed div COUNT`, shuffled per cycle. */
    fun indexFor(seed: PuzzleSeed): Int {
        val count = PICTURES.size.toLong()
        val cycle = seed.value.floorDiv(count)
        val position = seed.value.mod(count).toInt()
        val order = IntArray(PICTURES.size) { it }
        val random = PuzzleRandomV1(PuzzleSeed(cycle))
        for (last in order.lastIndex downTo 1) {
            val pick = random.nextInt(last + 1)
            val kept = order[last]
            order[last] = order[pick]
            order[pick] = kept
        }
        return order[position]
    }


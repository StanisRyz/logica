/**
 * Nonogram Generator V2: real pictures instead of random symmetric ones. The seed picks one of the
 * frozen [NonogramPictureSetV1] pictures — a cycle of the whole set in a seed-shuffled order, then
 * the next cycle — so consecutive seeds (the Daily's epoch days) never repeat a picture within a
 * cycle. Every picture is 10x10 and solvable by line logic alone; the difficulty is only its label.
 */
class NonogramGeneratorV2 : PuzzleGenerator<NonogramPuzzle> {
    override val type = PuzzleType.NONOGRAM
    override val version = GeneratorVersion(2)

    override fun generate(
        seed: PuzzleSeed,
        difficulty: Difficulty,
    ): NonogramPuzzle {
        val picture = NonogramPictureSetV1.pictureFor(seed)
        return NonogramPuzzle(PuzzleId(type, difficulty, seed, version), NonogramPictureSetV1.SIZE, picture)
    }
}

/**
